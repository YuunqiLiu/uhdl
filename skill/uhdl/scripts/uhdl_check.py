#!/usr/bin/env python3
"""Check the Verilog that UHDL generate() wrote, and point every message at the Python line.

    python uhdl_check.py OUT_DIR --top TOP [--sv FILE ...] [--no-synth]

1. Verilator lint with -Wall on OUT_DIR/filelist.f (plus the --sv files: imported SV sources or
   .f filelists). Each warning on a generated file is followed by the Python line from the
   `// file.py:line` comment that generate() put on that Verilog line.
2. Yosys synthesis with `check -assert`, for pure-Verilog designs (no --sv files): it catches
   combinational loops, multiple drivers and undriven nets after synthesis.

Prints CHECK PASS (exit 0), CHECK FAIL with the problems (exit 1), or CHECK NOT RUN when neither
tool is installed (exit 2). A tool that is not installed is reported as SKIPPED: that step was not
checked.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys

MSG = re.compile(r'^%(Warning|Error)(-[A-Z0-9_]+)?: ([^:\s][^:]*):(\d+):(?:(\d+):)? (.*)$')
SRC = re.compile(r'//\s*([\w.\-]+\.py:[\d,]+(?: [\w.\-]+\.py:[\d,]+)*(?: \.\.\.)?)\s*$')


def read_filelist(path):
    files = []
    for line in open(path):
        line = line.strip()
        if line and not line.startswith(('//', '#')):
            files.append(line)
    return files


def python_line(path, lineno, cache={}):
    if path not in cache:
        try:
            cache[path] = open(path, errors='replace').read().splitlines()
        except OSError:
            cache[path] = []
    lines = cache[path]
    if 0 < lineno <= len(lines):
        m = SRC.search(lines[lineno - 1])
        if m:
            return m.group(1)
    return None


def lint(top, gen_files, sv_args):
    exe = shutil.which('verilator')
    if not exe:
        return 'SKIPPED', ['verilator not found on PATH: lint was not run']
    cmd = [exe, '--lint-only', '-Wall', '-Wno-DECLFILENAME', '--top-module', top] + sv_args + gen_files
    r = subprocess.run(cmd, capture_output=True, text=True)
    gen = {os.path.realpath(f) for f in gen_files}
    ours, theirs, other = [], [], []
    for line in (r.stdout + r.stderr).splitlines():
        m = MSG.match(line)
        if not m:
            if line.startswith('%Error') and 'Exiting due to' not in line:
                other.append(line)
            continue
        kind, code, f, ln = m.group(1), (m.group(2) or '')[1:], m.group(3), int(m.group(4))
        if os.path.realpath(f) in gen:
            src = python_line(f, ln)
            ours.append('%s%s: %s:%d: %s\n      python: %s' % (
                kind, '-' + code if code else '', os.path.basename(f), ln, m.group(6),
                src or '(no source comment on this line; look at the signal or module named above)'))
        else:
            theirs.append(line)
    out = []
    if ours:
        out.append('%d message(s) on generated Verilog:' % len(ours))
        out += ['  ' + x for x in ours]
    if theirs:
        out.append('%d message(s) on imported SV files (not generated by UHDL):' % len(theirs))
        out += ['  ' + x for x in theirs[:20]]
    out += other
    # Warnings in hand-written SV are reported but are not the design's fault; errors anywhere fail.
    their_errors = any(l.startswith('%Error') for l in theirs)
    return ('FAIL' if ours or other or their_errors else 'PASS'), out


def synth(top, gen_files, has_sv):
    if has_sv:
        return 'SKIPPED', ['design imports SystemVerilog (--sv): Yosys synthesis check not run']
    exe = shutil.which('yosys')
    if not exe:
        return 'SKIPPED', ['yosys not found on PATH: synthesis check was not run']
    script = 'read_verilog %s; synth -top %s; check -assert' % (' '.join(gen_files), top)
    r = subprocess.run([exe, '-q', '-p', script], capture_output=True, text=True)
    if r.returncode == 0:
        return 'PASS', []
    tail = [l for l in (r.stdout + r.stderr).splitlines() if l.strip()][-15:]
    gen = {os.path.realpath(f): f for f in gen_files}
    out = []
    for l in tail:
        srcs = []
        for f, ln in re.findall(r'(\S+?\.s?v):(\d+)', l):
            if os.path.realpath(f) in gen:
                p = python_line(f, int(ln))
                if p and p not in srcs:
                    srcs.append(p)
        out.append('  ' + l + ('   [python: %s]' % ', '.join(srcs) if srcs else ''))
    return 'FAIL', ['yosys failed:'] + out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('out_dir', help='directory given to generate()')
    ap.add_argument('--top', required=True, help='top module name')
    ap.add_argument('--sv', action='append', default=[], help='imported SV source or .f filelist (repeatable)')
    ap.add_argument('--no-synth', action='store_true', help='skip the Yosys step')
    a = ap.parse_args()

    fl = os.path.join(a.out_dir, 'filelist.f')
    if not os.path.isfile(fl):
        print('CHECK FAIL: %s not found. Run generate(out_dir) first.' % fl)
        return 1
    gen_files = read_filelist(fl)
    sv_args = []
    for x in a.sv:
        sv_args += ['-f', x] if x.endswith('.f') else [x]

    results = [('lint', ) + lint(a.top, gen_files, sv_args)]
    if not a.no_synth:
        results.append(('synth', ) + synth(a.top, gen_files, bool(a.sv)))
    failed = False
    for step, status, lines in results:
        print('%-6s %s' % (step, status))
        for l in lines:
            print('    ' + l)
        failed |= status == 'FAIL'
    skipped = [s for s, st, _ in results if st == 'SKIPPED']
    if failed:
        print('CHECK FAIL')
        return 1
    if len(skipped) == len(results):
        print('CHECK NOT RUN: no checker installed (%s skipped). The design is NOT verified.' % ', '.join(skipped))
        return 2
    print('CHECK PASS' + (' (skipped: %s)' % ', '.join(skipped) if skipped else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
